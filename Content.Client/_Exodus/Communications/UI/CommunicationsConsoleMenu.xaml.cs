    public CommunicationsConsoleMenu()
    {
        IoCManager.InjectDependencies(this);
        _sprites = _entitySystems.GetEntitySystem<SpriteSystem>();
        RobustXamlLoader.Load(this);
        foreach (var child in MessageInput.Children)
        {
            if (child is VScrollBar scrollBar)
                _messageScrollBar = scrollBar;
        }
        FactionDashboard.RelationMapHost.AddChild(_relationMap);
        FactionDashboard.CorporationSearch.OnTextChanged += _ =>
        {
            FilterCorporations();
            FactionDashboard.CorporationScroll.VScroll = 0;
        };
        FactionDashboard.Tabs.OnTabChanged += _ => ResetWarConfirmations();

        MessageInput.Placeholder = new Rope.Leaf(_loc.GetString("comms-console-menu-announcement-placeholder"));

        MessageInput.OnTextChanged += _ => UpdateAnnouncementAvailability();

        AnnounceButton.OnPressed += _ => OnAnnounce?.Invoke(Rope.Collapse(MessageInput.TextRope));
        AnnounceButton.Disabled = !CanAnnounce;

        BroadcastButton.OnPressed += _ => OnBroadcast?.Invoke(Rope.Collapse(MessageInput.TextRope));
        BroadcastButton.Disabled = !CanBroadcast;

        AlertLevelButton.OnItemSelected += args =>
        {
            var metadata = AlertLevelButton.GetItemMetadata(args.Id);
            if (metadata is string cast)
                OnAlertLevel?.Invoke(cast);
        };

        FactionAlertLevelButton.OnItemSelected += args =>
        {
            var metadata = FactionAlertLevelButton.GetItemMetadata(args.Id);
            if (metadata is string cast)
                OnFactionAlertLevel?.Invoke(cast);
        };

        AlertLevelButton.Disabled = !AlertLevelSelectable;
        FactionDashboard.SectorColorBar.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.White };
        FactionDashboard.FactionColorBar.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.White };
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateWarAvailability();
        UpdateWarConfirmationAppearance();
        if (_factionLayout && _messageScrollBar != null)
            _messageScrollBar.Visible = _messageScrollBar.MaxValue > _messageScrollBar.Page;
    }

    public void UpdateSectorCode(string currentLevel, string? pendingLevel, TimeSpan pendingAt, Color color)
    {
        _sectorLevel = currentLevel;
        _pendingSector = pendingLevel;
        _pendingSectorAt = pendingAt;
        _sectorColor = color == default ? Color.White : color;
        _lastWarCountdownSecond = long.MinValue;
    }

    public void UpdateFactionAlerts(FactionAlertLevelState? state)
    {
        var previous = _factionAlerts;
        _factionAlerts = state;
        _lastWarCountdownSecond = long.MinValue;
        FactionAlertLevelButton.Visible = state != null;
        FactionDashboard.FactionCodeCard.Visible = state != null;
        if (state != null && previous != null && state.CurrentLevel == previous.CurrentLevel &&
            SameEntries(state.Levels, previous.Levels))
        {
            return;
        }

        FactionAlertLevelButton.Clear();
        if (state == null)
            return;

        foreach (var level in state.Levels)
        {
            FactionAlertLevelButton.AddItem(Loc.GetString(level.Name));
            FactionAlertLevelButton.SetItemMetadata(FactionAlertLevelButton.ItemCount - 1, level.Id);
            FactionAlertLevelButton.SetItemDisabled(FactionAlertLevelButton.ItemCount - 1,
                !level.Selectable || level.Id == state.CurrentLevel);
            if (level.Id == state.CurrentLevel)
            {
                FactionAlertLevelButton.Select(FactionAlertLevelButton.ItemCount - 1);
            }
        }
    }

    private string AlertName(string alert)
    {
        return _loc.TryGetString($"alert-level-{alert}", out var name) ? name : alert;
    }

    public void UpdateAnnouncementAvailability()
    {
        var tooLong = MessageInput.TextLength > _cfg.GetCVar(CCVars.ChatMaxAnnouncementLength);
        var empty = string.IsNullOrWhiteSpace(Rope.Collapse(MessageInput.TextRope));
        AnnounceButton.Disabled = !CanAnnounce || tooLong || empty;
        AnnounceButton.ToolTip = tooLong ? Loc.GetString("comms-console-message-too-long") : null;
        if (!_factionLayout)
            return;

        BroadcastButton.Disabled = !CanBroadcast || tooLong || empty;
        FactionDashboard.MessageCounter.Text = Loc.GetString("faction-console-message-count",
            ("count", MessageInput.TextLength), ("max", _cfg.GetCVar(CCVars.ChatMaxAnnouncementLength)));
        FactionDashboard.MessageCounter.FontColorOverride = tooLong ? Color.Salmon : Color.LightGray;
        FactionDashboard.MessageStatus.SetMessage(Loc.GetString(tooLong
            ? "comms-console-message-too-long"
            : empty ? "faction-console-message-empty"
            : !CanAnnounce ? "faction-console-message-cooldown" : "faction-console-message-ready"));
    }

    private static bool SameEntries<T>(List<T> first, List<T> second) where T : struct, IEquatable<T>
    {
        if (first.Count != second.Count)
            return false;

        for (var i = 0; i < first.Count; i++)
        {
            if (!first[i].Equals(second[i]))
                return false;
        }

        return true;
    }

    private static string FormatRemaining(TimeSpan duration)
    {
        var remaining = TimeSpan.FromSeconds(Math.Max(0, Math.Ceiling(duration.TotalSeconds)));
        return $"{(int)remaining.TotalHours:00}:{remaining.Minutes:00}:{remaining.Seconds:00}";
    }

    public void UpdateAlertLevels(List<string>? alerts, string currentAlert)
    {
        AlertLevelButton.Clear();

        if (alerts == null)
        {
            AlertLevelButton.AddItem(AlertName(currentAlert));
            AlertLevelButton.SetItemMetadata(AlertLevelButton.ItemCount - 1, currentAlert);
        }
        else
        {
            if (!alerts.Contains(currentAlert))
            {
                AlertLevelButton.AddItem(AlertName(currentAlert));
                AlertLevelButton.SetItemMetadata(0, currentAlert);
                AlertLevelButton.SetItemDisabled(0, true);
            }

            foreach (var alert in alerts)
            {
                AlertLevelButton.AddItem(AlertName(alert));
                AlertLevelButton.SetItemMetadata(AlertLevelButton.ItemCount - 1, alert);
                if (alert == currentAlert)
                    AlertLevelButton.Select(AlertLevelButton.ItemCount - 1);
            }
        }
    }
}
