    private readonly SpriteSystem _sprites;
    private readonly VScrollBar? _messageScrollBar;

    private readonly Dictionary<ProtoId<TerritoryFactionPrototype>, WarDeclarationRow> _warRows = new();
    private readonly HashSet<ProtoId<TerritoryFactionPrototype>> _seenWarTargets = new();
    private readonly List<ProtoId<TerritoryFactionPrototype>> _staleWarTargets = new();
    private readonly FactionRelationMap _relationMap = new();
    private readonly List<(Control Control, string Search)> _corporationRows = new();

    private bool _warCodeAllowsWar;
    private string _warSourceName = string.Empty;
    private long _lastWarCountdownSecond = long.MinValue;
    private bool _hasWarState;
    private bool _warRoundRunning;
    private bool _factionLayout;
    private TimeSpan _allianceBreakCooldown;
    private WarDeclarationConsoleState? _warState;
    private FactionAlertLevelState? _factionAlerts;
    private string _sectorLevel = string.Empty;
    private string? _pendingSector;
    private TimeSpan _pendingSectorAt;
    private Color _sectorColor = Color.White;
    private Color _shownSectorColor;
    private Color _shownFactionColor;
    private bool _sectorColorReady;
    private bool _factionColorReady;

